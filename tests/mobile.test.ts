test("build arguments keep project, license and settings paths as separate argv entries", () => {
  const args = constructIgorBuildArgs(
    ctx,
    {
      igorPath: "/igor",
      licenseFile: "/protected/license with spaces.plist",
      prefabsDir: "/prefabs",
      runtimeDir: "/runtime",
      target: "ios",
      cacheDir: "/cache/invocation-one",
      projectPath: parseProjectPath(ctx, "/project/Game.yyp"),
      projectToolPath: "/project-tool",
      verbose: false,
      runtime: "YYC",
      userDir: "/cache/invocation-one/user",
    },
    "Package",
  );
  assert.equal(
    args[args.indexOf("-lf") + 1],
    "/protected/license with spaces.plist",
  );
  assert.equal(args[args.indexOf("-uf") + 1], "/cache/invocation-one/user");
  assert.deepEqual(args.slice(-3), ["--", "ios", "Package"]);
  assert.equal(args.includes("-jsonErrors"), false);
});

