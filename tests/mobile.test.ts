const ctx = buildContext(process);
async function temporary(t: { after: (fn: () => Promise<void>) => void }) {
  const root = await mkdtemp(path.join(tmpdir(), "gm-ios-"));
  t.after(() => rm(root, { recursive: true, force: true }));
  return root;
}
async function file(p: string, data: string | Uint8Array = "") {
  await mkdir(path.dirname(p), { recursive: true });
  await writeFile(p, data);
}
test("reject missing generation even when another invocation has an old project", async (t) => {
  const root = await temporary(t);
  await file(path.join(root, "old/Game.xcodeproj/project.pbxproj"));
  await mkdir(path.join(root, "fresh"));
  await assert.rejects(
    findGeneratedIosProject(ctx, path.join(root, "fresh")),
    /found 0/,
  );
});
test("accept one generated project and ignore Pods; reject ambiguous outputs", async (t) => {
  const root = await temporary(t);
  const project = path.join(root, "output/Game.xcodeproj");
  await file(path.join(project, "project.pbxproj"));
  await file(path.join(root, "output/Pods/Pods.xcodeproj/project.pbxproj"));
  assert.equal(await findGeneratedIosProject(ctx, root), project);
  await file(path.join(root, "output/Other.xcodeproj/project.pbxproj"));
  await assert.rejects(findGeneratedIosProject(ctx, root), /found 2/);
});
test("project discovery never follows symlinks outside the invocation", async (t) => {
  const root = await temporary(t);
  await file(path.join(root, "outside/Game.xcodeproj/project.pbxproj"));
  await mkdir(path.join(root, "fresh"));
  await symlink(path.join(root, "outside"), path.join(root, "fresh/link"));
  await assert.rejects(
    findGeneratedIosProject(ctx, path.join(root, "fresh")),
    /found 0/,
  );
});
test("GameMaker trailing commas do not change strings", () => {
  assert.deepEqual(
    parseYy('{"text": "literal ,} and \\"quoted\\"", "items":[1,],}'),
    { text: 'literal ,} and "quoted"', items: [1] },
  );
});
test("reject unsafe framework archive destinations", () => {
  for (const name of [
    "/absolute",
    "../escape",
    "Fw/../../escape",
    "a//b",
    "a/./b",
    "a\\b",
    "C:/escape",
    "\0x",
  ]) {
    assert.equal(safeArchivePath(name), false, name);
  }
  assert.equal(safeArchivePath("Name.xcframework/ios-arm64/Name"), true);
});
async function frameworkFixture(
  t: { after: (fn: () => Promise<void>) => void },
  entries: Record<string, Uint8Array>,
) {
  const root = await temporary(t);
  const project = parseProjectPath(ctx, path.join(root, "source/Game.yyp"));
  await file(
    project,
    '{"resources":[{"id":{"path":"extensions/Test/Test.yy"}},],}',
  );
  const zip = path.join(
    root,
    "source/extensions/Test/iOSSourceFromMac/Test.zip",
  );
  await file(zip, zipSync(entries));
  const generated = path.join(root, "generated");
  await mkdir(generated);
  return { root, project, generated, zip };
}
test("prepare referenced framework ZIPs and allow identical contents already generated by Igor", async (t) => {
  const bytes = Buffer.from("framework");
  const f = await frameworkFixture(t, { "Test.xcframework/Info.plist": bytes });
  await prepareIosFrameworks(ctx, f.project, f.generated);
  await prepareIosFrameworks(ctx, f.project, f.generated);
  assert.deepEqual(
    await readFile(path.join(f.generated, "Fw/Test.xcframework/Info.plist")),
    bytes,
  );
  await file(
    path.join(f.generated, "Fw/Test.xcframework/Info.plist"),
    "different",
  );
  await assert.rejects(
    prepareIosFrameworks(ctx, f.project, f.generated),
    /Conflicting/,
  );
});
test("framework ZIP traversal fails without writing outside generated project", async (t) => {
  const f = await frameworkFixture(t, { "../escape": Buffer.from("bad") });
  await assert.rejects(
    prepareIosFrameworks(ctx, f.project, f.generated),
    /Unsafe/,
  );
  await assert.rejects(readFile(path.join(f.generated, "escape")), /ENOENT/);
});
test("framework preparation refuses preexisting links", async (t) => {
  const f = await frameworkFixture(t, {
    "Test.xcframework/Info.plist": Buffer.from("new"),
  });
  await file(path.join(f.root, "outside/Info.plist"), "preserve");
  await mkdir(path.join(f.generated, "Fw"));
  await symlink(
    path.join(f.root, "outside"),
    path.join(f.generated, "Fw/Test.xcframework"),
  );
  await assert.rejects(
    prepareIosFrameworks(ctx, f.project, f.generated),
    /symbolic link/,
  );
  assert.equal(
    await readFile(path.join(f.root, "outside/Info.plist"), "utf8"),
    "preserve",
  );
});
test("runner staged by Xcode must match selected architecture and bytes", async (t) => {
  const root = await temporary(t);
  await file(path.join(root, "project/ios-arm64/libyoyo_yyc.a"), "device");
  await file(
    path.join(root, "project/ios-simulator/libyoyo_yyc_sim.a"),
    "simulator",
  );
  const expected = await runnerHashes(ctx, path.join(root, "project"));
  const staged = path.join(
    root,
    "DerivedData/Build/Products/Release-iphoneos/libyoyo_yyc.a",
  );
  await file(staged, "device");
  await verifyStagedIosRunner(
    ctx,
    path.join(root, "DerivedData"),
    expected,
    false,
  );
  await file(staged, "wrong runtime");
  await assert.rejects(
    verifyStagedIosRunner(ctx, path.join(root, "DerivedData"), expected, false),
    /distribution blocked/,
  );
});
