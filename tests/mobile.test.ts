import {
  parseToolchainVersion,
  toolchainVersionToString,
} from "../src/toolchain";
test("exact custom runtime keeps its suffix through parsing and configuration", () => {
  const selected = parseToolchainVersion("GMS2@2024.14.4.268-c1");
  assert.deepEqual(selected, {
    type: "GMS2",
    version: [2024, 14, 4, 268],
    customVersion: "2024.14.4.268-c1",
  });
  assert.equal(toolchainVersionToString(selected), "GMS2@2024.14.4.268-c1");
  for (const value of [
    "2024.14.4-c1",
    "2024.14.4.268-C1",
    "2024.14.4.268-c0",
    "2024.14.4.268-c01",
    "2024.14.4.268-c1@extra",
  ]) {
    assert.throws(() => parseToolchainVersion("GMS2@" + value));
  }
  assert.equal(
    toolchainVersionToString(parseToolchainVersion("GMS2@2024.14.4.268")),
    "GMS2@2024.14.4.268",
  );
});
